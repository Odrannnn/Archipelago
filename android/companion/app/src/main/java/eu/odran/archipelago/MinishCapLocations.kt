    fun checkedIds(memory: ByteArray): Set<Long> {
        require(memory.size == RAM_LENGTH)
        val checked = mutableSetOf<Long>()
        var index = 0
        while (index < ordinary.size) {
            val id = ordinary[index]
            val address = ordinary[index + 1]
            val mask = ordinary[index + 2].toInt()
            val value = memory[(address - RAM_START).toInt()].toInt() and 0xff
            if (value or mask == value) checked += id
            index += 3
        }
        val goron0 = memory[(0x2CA3L - RAM_START).toInt()].toInt() and 0xff
        val goron1 = memory[(0x2CA4L - RAM_START).toInt()].toInt() and 0xff
        val restocks = Integer.bitCount(goron0 and 0xC0) + Integer.bitCount(goron1 and 0x03)
        val purchases = (goron1 and 0x1C) ushr 2
        if (restocks in 0..4) {
            repeat(3) { slot -> if (purchases and (1 shl slot) != 0) checked += 6029034L + restocks * 3 + slot }
        }
        val cucco = memory[(0x2CA5L - RAM_START).toInt()].toInt() and 0xff
        val completedRounds = ((cucco ushr 3) + if (cucco and 0x80 != 0) 1 else 0).coerceAtMost(10)
        repeat(completedRounds) { round -> checked += 6029068L + round }
        return checked
    }
